
function vmSig = virtualMic(Mics, Theta_new, Phi_new)
% virtualMic Synthesizes virtual microphone signals using spherical harmonics.
%
%   vmSig = virtualMic(Mics, Theta_new, Phi_new) synthesizes the signals
%   of virtual microphones at the specified elevation and azimuth angles
%   using the signals recorded by the physical microphones.
%
% Inputs:
%   Mics      - Signals recorded by the physical microphones.
%   Theta_new - Elevation angles of the virtual microphones (radians).
%   Phi_new   - Azimuth angles of the virtual microphones (radians).
%
% Output:
%   vmSig     - Synthesized signals of the virtual microphones.
%
% Author: Amin Aslanzadeh
% Date:   May, 2025

    %% Add Required Function Paths
    addpath('../math');

    %% Physical Microphone Positions
    Theta = [23*pi/60, ...
             pi/2, ...
             37*pi/60, ...
             pi/2, ...
             8*pi/45, ...
             11*pi/36, ...
             pi/2, ...
             25*pi/36, ...
             37*pi/45, ...
             25*pi/36, ...
             pi/2, ...
             11*pi/36, ...
             7*pi/60, ...
             29*pi/90, ...
             121*pi/180, ...
             53*pi/60, ...
             23*pi/60, ...
             pi/2, ...
             37*pi/60, ...
             pi/2, ...
             8*pi/45, ...
             11*pi/36, ...
             pi/2, ...
             25*pi/36, ...
             37*pi/45, ...
             25*pi/36, ...
             pi/2, ...
             11*pi/36, ...
             7*pi/60, ...
             29*pi/90, ...
             61*pi/90, ...
             53*pi/60];

    Phi = [0, ...
           8*pi/45, ...
           0, ...
           82*pi/45, ...
           0, ...
           pi/4, ...
           23*pi/60, ...
           pi/4, ...
           0, ...
           7*pi/4, ...
           97*pi/60, ...
           7*pi/4, ...
           91*pi/180, ...
           pi/2, ...
           pi/2, ...
           89*pi/180, ...
           pi, ...
           53*pi/45, ...
           pi, ...
           37*pi/45, ...
           pi, ...
           5*pi/4, ...
           83*pi/60, ...
           5*pi/4, ...
           pi, ...
           3*pi/4, ...
           37*pi/60, ...
           3*pi/4, ...
           269*pi/180, ...
           3*pi/2, ...
           3*pi/2, ...
           271*pi/180];

    %% Spherical Harmonic Parameters
    numMics = length(Theta);  % Number of physical microphones
    N = 4;                    % Spherical harmonic order

    Y = sh2(N, Theta, Phi);
    Yq = conj(Y);

    %% Virtual Microphone Synthesis
    virtual_Mic_num = length(Theta_new);
    vmSig = zeros(virtual_Mic_num, size(Mics, 2));

    for q = 1:virtual_Mic_num
        Y_new = sh2(N, Theta_new(q), Phi_new(q));
        Y_total = Yq' .* Y_new';

        signal = real((4*pi/numMics) * Mics' * Y_total);
        vmSig(q, :) = sum(signal, 2);
    end

end
